const { Telegraf, Markup } = require('telegraf');
const axios = require('axios');
require('dotenv').config();

const bot = new Telegraf(process.env.TELEGRAM_TOKEN);

const auditLogs = [];

function logEvent(nivel, mensagem) {
    const timestamp = new Date().toISOString().replace('T', ' ').substring(0, 19);
    console.log(`${timestamp} [${nivel}] ${mensagem}`);
}

function registrarAuditoria({ source, category, severity, confidence, status, risk_score, raw_reference, dataType = 'REAL' }) {
    const event = {
        event_id: 'EVT-' + Math.random().toString(36).substring(2, 8).toUpperCase(),
        timestamp: new Date().toISOString(),
        source, category, severity, confidence, status, risk_score,
        data_type: dataType,
        raw_reference
    };
    auditLogs.unshift(event);
    if (auditLogs.length > 30) auditLogs.pop();
    return event;
}

// Novo Menu Interativo Avançado SOC (Tier-3)
function menuSOCAvancado() {
    return Markup.inlineKeyboard([
        [Markup.button.callback('📊 Dashboard', 'cmd_dashboard'), Markup.button.callback('📈 Metrics', 'cmd_metrics')],
        [Markup.button.callback('🚨 Incidents', 'cmd_incidents'), Markup.button.callback('⏳ Timeline', 'cmd_timeline')],
        [Markup.button.callback('📋 Briefing', 'cmd_briefing'), Markup.button.callback('🛰️ Sources', 'cmd_sources')],
        [Markup.button.callback('🩺 Health Check', 'cmd_health'), Markup.button.callback('🧪 Demo Mode', 'cmd_demo')]
    ]);
}

